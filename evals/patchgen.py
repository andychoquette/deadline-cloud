"""Turn a winning docstring variant into a reviewable artifact.

Given a revisions dict ({command_path: {help, options}}) that BEAT baseline past the
gate, emit a human-readable proposal the team can turn into a real PR against the
`deadline` CLI source (src/deadline/client/cli/_groups/*.py).

POC scope: emits a Markdown proposal (current help -> proposed help, per command,
with the measured evidence). A future version can locate the exact docstring/option
in the installed source and emit a unified diff automatically; for now we keep it as
a clear, copy-pasteable proposal so a human stays in the loop before any source edit.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import autodraft

# Map a CLI command path to the source file where its help lives (from research).
_SOURCE_FILE = {
    "bundle": "src/deadline/client/cli/_groups/bundle_group.py",
    "bundle submit": "src/deadline/client/cli/_groups/bundle_group.py",
    "bundle gui-submit": "src/deadline/client/cli/_groups/bundle_group.py",
    "job": "src/deadline/client/cli/_groups/job_group.py",
    "job get": "src/deadline/client/cli/_groups/job_group.py",
    "job logs": "src/deadline/client/cli/_groups/job_group.py",
    "job list": "src/deadline/client/cli/_groups/job_group.py",
}


def emit_proposal(revisions: dict, evidence: dict, out_path: Path) -> Path:
    """Write a Markdown docstring-change proposal for the winning revisions."""
    revs = revisions.get("autodrafted") or revisions.get("revised") or {}
    lines = ["# Proposed `deadline` CLI docstring improvements", ""]

    # Evidence header.
    sd = evidence.get("success_delta")
    td = evidence.get("turn_delta")
    ld = evidence.get("tool_delta")
    cd = evidence.get("cost_delta_usd")
    lines += [
        "## Why (measured by deadline-evals)",
        "",
        f"- success delta: {sd:+.0%}" if sd is not None else "",
        f"- median turns delta: {td:+g}" if td is not None else "",
        f"- median tool-calls delta: {ld:+g}" if ld is not None else "",
        f"- median cost delta: ${cd:+.4f}" if cd is not None else "",
        "",
        "Deltas are candidate-minus-baseline; negative turns/tools/cost = improvement.",
        "",
    ]

    for cmd_path, rev in revs.items():
        src = _SOURCE_FILE.get(cmd_path, "(locate in src/deadline/client/cli/_groups/)")
        lines += [f"## `deadline {cmd_path}`", "", f"**Source:** `{src}`", ""]
        current = autodraft.current_help(cmd_path).strip()
        lines += ["### Current help", "```", current, "```", ""]
        if "help" in rev:
            lines += ["### Proposed help (docstring)", "```", rev["help"].strip(), "```", ""]
        opts = rev.get("options") or {}
        if opts:
            lines += ["### Proposed option help (`@click.option(help=...)`)", ""]
            for oname, ohelp in opts.items():
                lines += [f"- `--{oname.replace('_', '-')}`: {ohelp}"]
            lines += [""]

    lines += [
        "---",
        "_Generated by deadline-evals. Review, then transcribe into the docstrings/"
        "`@click.option(help=...)` in the source file(s) above and open a PR against a "
        "fork of aws-deadline/deadline-cloud._",
    ]
    out_path.write_text("\n".join(l for l in lines if l is not None))
    return out_path
